"""Block 05, why: the sum 1 + 2 + … + 100 written twice and added column by column."""
from fig import Fig

TEXT = {
    'uk': ('Сума від 1 до 100 записана двічі: зліва направо і справа наліво. Кожен стовпчик дає 101, стовпчиків 100, і кожне число пораховано двічі, тому сума дорівнює 101 · 100 / 2 = 5050.',
           'Сума арифметичної прогресії: сто пар по 101, поділені на два.', 'кожна пара'),
    'ru': ('Сумма от 1 до 100 записана дважды: слева направо и справа налево. Каждый столбик даёт 101, столбиков 100, и каждое число посчитано дважды, поэтому сумма равна 101 · 100 / 2 = 5050.',
           'Сумма арифметической прогрессии: сто пар по 101, делённые на два.', 'каждая пара'),
}


def figure(lang):
    label, caption, each = TEXT[lang]
    f = Fig(132)
    top = ['1', '2', '3', '…', '99', '100']
    bot = ['100', '99', '98', '…', '2', '1']
    xs = [40, 84, 128, 172, 216, 268]
    for x, a, b in zip(xs, top, bot):
        f.text(x, 30, a, size=14, anchor='middle')
        f.text(x, 56, b, size=14, anchor='middle')
        if a != '…':
            f.line(x - 16, 66, x + 16, 66, w=1)
            f.text(x, 86, '101', size=13, anchor='middle', bold=True, accent=True)
    f.text(14, 30, '+', size=14, op=0)
    f.text(160, 118, each + ': 101,  2S = 101 · 100', size=12, anchor='middle', op=0.8)
    return f, label, caption
